# 但是 input() 函式非常懶惰，它不管你輸入什麼，通通都會把它打包成「字串 (str)」。
# 就像你把「數字 100」裝進「文字信封」裡，電腦會覺得那是文字，不能拿來加減。

print("\n[系統訊息]：請輸入目前手電筒的剩餘電力...")
current_power = input("輸入電力數值: ")

# --- 實驗區：請試著換換看下面三種組合，把正確的那個「解開註解」來執行 ---

