# needed_power = 500 - current_power 

# 組合 B (字串化)：這也會爆炸，因為它會變成把文字重複印出來
# needed_power = "500" - current_power 

# 組合 C (數字化)：這是正確的嗎？使用 int() 把「文字信封」拆開，拿出裡面的整數
# needed_power = 500 - int(current_power)

# ------------------------------------------------------------------------------
# 💡 提示給特務：
# 1. str(資料) -> 把東西變成「文字」
# 2. int(資料) -> 把東西變成「整數數字」
# 3. 如果你的 current_power 是 "100"，經過 int("100") 就會變成真正的 100 了！
